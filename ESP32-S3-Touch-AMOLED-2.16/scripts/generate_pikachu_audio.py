#!/usr/bin/env python3
"""Embed the selected 2.2-second WAV as mono PCM in flash; no decoder needed."""
from pathlib import Path
import hashlib
import struct
import wave

APP = Path(__file__).resolve().parents[1] / 'examples/arduino/08_OrbitClock'


def main():
    source = APP / 'pikachu_effect.wav'
    with wave.open(str(source), 'rb') as wav:
        if (wav.getframerate(), wav.getnchannels(), wav.getsampwidth(), wav.getnframes()) != (16000, 1, 2, 35200):
            raise ValueError('Expected 2.2 seconds of 16000 Hz, mono, 16-bit PCM')
        pcm = wav.readframes(wav.getnframes())
    samples = struct.unpack('<35200h', pcm)
    (APP / 'pikachu_pcm.h').write_text('''#pragma once
#include <stdint.h>
#ifdef __cplusplus
extern "C" {
#endif
enum { PIKACHU_SAMPLE_RATE = 16000, PIKACHU_SAMPLE_COUNT = 35200 };
extern const int16_t pikachu_pcm[PIKACHU_SAMPLE_COUNT];
#ifdef __cplusplus
}
#endif
''')
    lines = [
        '// Generated by scripts/generate_pikachu_audio.py from pikachu_effect.wav.',
        '// WAV SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
        '#include "pikachu_pcm.h"',
        'const int16_t pikachu_pcm[PIKACHU_SAMPLE_COUNT] = {'
    ]
    lines += ['  ' + ','.join(map(str, samples[i:i + 16])) + ',' for i in range(0, len(samples), 16)]
    lines += ['};', '']
    (APP / 'pikachu_pcm.c').write_text('\n'.join(lines))
    print(f'Embedded {len(samples)} samples, {len(pcm)} bytes, 2.200 seconds')


if __name__ == '__main__':
    main()
